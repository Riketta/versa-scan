//! Identifier newtypes. Opaque strings with light structural validation -
//! they must survive bus round-trips, filesystem names, and log lines.

use std::fmt;

/// Validation failure for an identifier newtype.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("invalid identifier: {reason}")]
pub struct InvalidId {
    reason: String,
}

fn validate(value: &str, kind: &str) -> Result<(), InvalidId> {
    if value.is_empty() {
        return Err(InvalidId { reason: format!("{kind} must not be empty") });
    }
    if value.len() > 128 {
        return Err(InvalidId { reason: format!("{kind} longer than 128 chars") });
    }
    if value.chars().any(char::is_whitespace) {
        return Err(InvalidId { reason: format!("{kind} must not contain whitespace") });
    }
    Ok(())
}

macro_rules! string_id {
    ($(#[$doc:meta])* $name:ident) => {
        $(#[$doc])*
        #[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub struct $name(String);

        impl $name {
            /// Validates and wraps a raw identifier value.
            pub fn new(value: impl Into<String>) -> Result<Self, InvalidId> {
                let value = value.into();
                validate(&value, stringify!($name))?;
                Ok(Self(value))
            }

            pub fn as_str(&self) -> &str {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }
    };
}

string_id!(
    /// Unique identity of one sample within the system. Generated by the
    /// submitting side (vscli), travels unchanged through the whole pipeline.
    SampleId
);
string_id!(
    /// Correlation of a request/report pair, owned by the requester.
    CorrelationId
);
string_id!(
    /// Slug of a scanner implementation (e.g. `clamd`, `defender`, `debug`).
    /// Names the request queue/subject the sample is dispatched to.
    ScannerId
);
string_id!(
    /// Identity of one batch (one scanner run over a group of samples).
    /// Generated by the planner when the batch is opened.
    BatchId
);

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use super::*;

    #[test]
    fn rejects_empty() {
        assert!(SampleId::new("").is_err());
        assert!(SampleId::new("   ").is_err());
    }

    #[test]
    fn rejects_whitespace_inside() {
        assert!(SampleId::new("a b").is_err());
    }

    #[test]
    fn rejects_overlong() {
        let long = "a".repeat(129);
        assert!(SampleId::new(long).is_err());
    }

    #[test]
    fn round_trips_display() {
        let id = SampleId::new("abc-123").unwrap();
        assert_eq!(id.to_string(), "abc-123");
        assert_eq!(id.as_str(), "abc-123");
    }
}
